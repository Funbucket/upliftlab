"""Writes web/catalog.js: the dataset and algorithm catalog plus a pre-computed example run, both from the engine.

The example is what the compare tab shows before anyone runs anything. Run after changing the engine or algorithms.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'engine'))
from upliftlab import __version__, bridge, datasets  # noqa: E402

EXAMPLE = {'dataset': 'synthetic/base', 'algorithms': ['random_baseline', 'x_learner', 't_learner', 'r_learner', 'dml', 'duality_r_learner'],
           'cycles': 8, 'explore': .2, 'target': .4, 'seed': 42, 'mode': 'budget', 'budget': .4, 'baseLearner': 'ridge'}
builtins = {a['id']: a for a in bridge.builtins()}
bridge.state.update(runtime='local')
record = bridge.run_all(EXAMPLE['dataset'], [{'id': i, 'name': builtins[i]['name'], 'code': builtins[i]['code']} for i in EXAMPLE['algorithms']],
                        EXAMPLE['cycles'], EXAMPLE['explore'], EXAMPLE['target'], EXAMPLE['seed'], mode=EXAMPLE['mode'], budget=EXAMPLE['budget'])
record['plan']['runtime'] = 'local'


def entry(a):
    """Catalog fields only. Library names without status: whether a runtime has them is that runtime's answer (info())."""
    return {**{k: a[k] for k in ('id', 'name', 'summary', 'file')}, 'libraries': [{'module': l['module'], 'package': l['package']} for l in a['libraries']]}


catalog = {'engine': __version__, 'datasets': datasets.catalog(), 'algorithms': [entry(a) for a in builtins.values()],
           'templates': [entry(t) for t in bridge.templates()]}
example = {'config': EXAMPLE, 'runtime': 'local', **record}
text = ('// Generated by scripts/build-catalog.py from engine/. Do not edit.\n'
        f'export const CATALOG = {json.dumps(catalog, ensure_ascii=False)};\n'
        f'export const EXAMPLE = {json.dumps(example, ensure_ascii=False, separators=(",", ":"))};\n')
(root / 'web' / 'catalog.js').write_text(text, encoding='utf-8')
print(f'Wrote web/catalog.js ({len(text) // 1024} KB) · example leader {record["summary"]["leader"]}')
