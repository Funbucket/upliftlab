// Copies the Python engine into web/engine-files.js so the browser runs the same files as the local edition.
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), engine = path.join(root, 'engine');
const skip = new Set(['upliftlab/server.py', 'upliftlab/__main__.py']), files = {};
async function walk(dir) {
  for (const entry of await readdir(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name), rel = path.relative(engine, full).split(path.sep).join('/');
    if (entry.isDirectory()) { if (entry.name !== '__pycache__') await walk(full); }
    else if (rel.endsWith('.py') && !skip.has(rel)) files[rel] = await readFile(full, 'utf8');
  }
}
await walk(path.join(engine, 'upliftlab'));
await writeFile(path.join(root, 'web/engine-files.js'), '// Generated by scripts/bundle-engine.mjs from engine/. Do not edit.\nexport const ENGINE_FILES = ' + JSON.stringify(files, Object.keys(files).sort()) + ';\n');
console.log(`Bundled ${Object.keys(files).length} engine files.`);
